"""codegen_param_table.py — emits the per-command KNOWN-PARAM table for the plugin.

Why this exists
---------------
No command validates unknown parameters. `Params->TryGet*Field(TEXT("x"), Out)`
returns false and leaves the default in place SILENTLY, in EVERY command
("ignored if unrecognized" is even a documented pattern in several domains). So a
typo in a param key reads EXACTLY like "that option did nothing" — and that is not
a theoretical cost: a `build_blueprint_graph` EXCEPTION_ACCESS_VIOLATION that killed
the editor was triggered by a payload whose sub-command params sat at the ROOT level
instead of inside `params:{}`.

The data to answer "nobody reads that key" already exists: `Resources/command_catalog.json`
is autogenerated from the `// MCP:` annotations in the C++ and lists, per command,
every param with its name/type/required flag. This script turns that into a static
C++ table the bridge can consult once per dispatch, so an unrecognized key gets
REPORTED (never rejected — see the bridge hook) instead of swallowed.

What it emits
-------------
  * `Source/UEAgent/Public/McpCommandParamTable.gen.h`
        the tiny public API (declarations only, so the header stays cheap to include)
  * `Source/UEAgent/Private/McpCommandParamTable.gen.cpp`
        the data: ONE flat array of string literals (`cmd, p1, p2, ..., nullptr`
        per command, plus a final `nullptr` sentinel) walked ONCE into a
        function-local `static const TMap<FName, TSet<FName>>`. Deliberately not
        one `Map.Add(...)` statement PER COMMAND: one array of literals is far
        smaller object code and compiles in a fraction of the time. How many
        commands that is today, when the number matters:
          python -c "import json;print(sum(len(d['commands']) for d in json.load(open('Resources/command_catalog.json'))['domains']))"

`.gen.h` / `.gen.cpp`, NOT `.generated.h`: `<Name>.generated.h` is the suffix
UnrealHeaderTool reserves for its OWN artifacts (it emits them into
`Intermediate/Build/.../Inc/UEAgent/UHT/`). Naming a hand-emitted source file the
same way puts it one `UCLASS` away from an include that resolves to the wrong file
— not worth the risk for a suffix.

Both files are ASCII-only on purpose: they land in compiled C++ and MSVC warns
(C4819) on non-ASCII bytes in a source file.

Determinism: commands and their params are emitted sorted, so re-running on an
unchanged catalog reproduces the files byte for byte (`--check` relies on that).

ORDER MATTERS: this reads `command_catalog.json`, which is itself generated from
the C++ by codegen_command_catalog.py. Always run
`codegen_command_catalog.py --write` FIRST — a stale catalog produces a stale
table, and a stale table reports a param that DOES exist as unknown, which is the
fastest way to teach everyone to ignore the field.

Usage:
  python Tools/codegen_param_table.py            # report only (default)
  python Tools/codegen_param_table.py --write    # regenerate the .h/.cpp
  python Tools/codegen_param_table.py --check    # exit non-zero if the files drifted
"""

from __future__ import annotations
import argparse
import json
import os
import sys

# ---------------------------------------------------------------------------
# Paths (derived from the plugin root by _paths.py, like every other script)
# ---------------------------------------------------------------------------
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _paths  # noqa: E402
from check_copyright import NOTICE  # noqa: E402

CATALOG_JSON = _paths.CATALOG_JSON
PLUGIN_SRC = _paths.SOURCE_DIR
# `.gen.*`, never `.generated.*`: that suffix belongs to UnrealHeaderTool (see the
# module docstring). Both names live ONLY here -- the emitted #include is derived
# from HEADER_NAME, so a rename is a one-line change.
HEADER_NAME = "McpCommandParamTable.gen.h"
SOURCE_NAME = "McpCommandParamTable.gen.cpp"
OUT_H = os.path.join(PLUGIN_SRC, "Public", HEADER_NAME)
OUT_CPP = os.path.join(PLUGIN_SRC, "Private", SOURCE_NAME)

GENERATOR = "Tools/codegen_param_table.py"
SOURCE = "Resources/command_catalog.json"

# ---------------------------------------------------------------------------
# THE ONE LIST OF PROTOCOL KEYS (keys that ride in the request but are NOT
# params of the command). Every entry carries the evidence
# of where it comes from -- the comment travels into the generated .cpp so the
# next reader does not have to trust this file.
#
# Anything NOT listed here and NOT in the command's catalog params is reported.
# Note the order of checks in the C++ makes this list harmless for real params:
# a key that IS a known param of the command (e.g. `type` for spawn_actor,
# `command` for execute_console_command) matches the known set FIRST and never
# reaches this list.
# ---------------------------------------------------------------------------
PROTOCOL_KEYS: list[tuple[str, str]] = [
    ("command_type",
     "sub-command envelope key of `execute_batch` items and of build_blueprint_graph nodes "
     "(UEAgentMetaCommands.cpp HandleBatch)"),
    ("command",
     "alternative spelling of the command name used by hand-written callers"),
    ("id",
     "per-sub-command correlation id in the documented payload shape "
     "{\"id\":..., \"command_type\":..., \"params\":{...}}"),
    ("track_collateral_dirty",
     "CROSS-CUTTING dispatcher param read for EVERY command by "
     "McpCollateralDirty::ShouldTrack (UEAgentBridge.cpp); it is in no "
     "command's catalog entry, so without this line it would be a false positive "
     "on every call that opts into collateral tracking"),
    ("force",
     "CROSS-CUTTING dispatcher param: the override valve of BOTH PIE gates -- "
     "CheckPIEOwnershipGuard (start_/stop_play_in_editor, where `force` IS a "
     "catalogued param and so is matched there FIRST) and CheckPIESafetyGuard, "
     "which reads it on any command listed in McpPieSafety.gen.h. Without "
     "this line every forced compile/save would also report force as an unknown "
     "param, which is how a field earns being ignored"),
]

# Wrap the param literals of a command at roughly this column.
WRAP_COLUMN = 100


# ---------------------------------------------------------------------------
# Catalog -> {command: [param names]}
# ---------------------------------------------------------------------------
def load_catalog(path: str) -> dict[str, list[str]]:
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    out: dict[str, list[str]] = {}
    for domain in data.get("domains", []):
        for cmd in domain.get("commands", []):
            name = cmd.get("name")
            if not name:
                continue
            names = sorted({p["name"] for p in cmd.get("params", []) if p.get("name")})
            # Same command in two domains would be a catalog bug; union the params
            # rather than silently dropping one of the two entries.
            if name in out:
                out[name] = sorted(set(out[name]) | set(names))
            else:
                out[name] = names
    return dict(sorted(out.items()))


def validate(table: dict[str, list[str]]) -> list[str]:
    """A name that is not a plain identifier would produce a C++ literal we cannot
    trust (quotes/backslashes/non-ASCII). The catalog has never contained one; if it
    ever does, fail loudly instead of emitting broken C++."""
    problems: list[str] = []
    def bad(s: str) -> bool:
        return (not s) or (not s.isascii()) or any(
            c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_" for c in s)
    for cmd, params in table.items():
        if bad(cmd):
            problems.append(f"command name is not a plain identifier: {cmd!r}")
        for p in params:
            if bad(p):
                problems.append(f"param name is not a plain identifier: {cmd}.{p!r}")
    return problems


# ---------------------------------------------------------------------------
# Emit
# ---------------------------------------------------------------------------
def banner(kind: str) -> str:
    return (
        f"{NOTICE}\n\n"
        f"// AUTO-GENERATED by {GENERATOR} from {SOURCE} -- DO NOT EDIT BY HAND.\n"
        f"// To regenerate, IN THIS ORDER (the table comes from the catalog, the catalog from the C++):\n"
        f"//   python Tools/codegen_command_catalog.py --write\n"
        f"//   python {GENERATOR} --write\n"
        f"//\n"
        f"// {kind}"
    )


def render_header(table: dict[str, list[str]]) -> str:
    n_cmds = len(table)
    n_params = sum(len(v) for v in table.values())
    lines: list[str] = []
    a = lines.append
    a(banner("Public API of the known-param table (declarations only; the data "
             "lives in the .cpp)."))
    a("//")
    a("// The problem it solves: a `TryGet*Field` that fails returns the default SILENTLY,")
    a("// in every command, so a typo in a param key reads exactly like \"that option did")
    a("// nothing\" (sending the params at the root level instead of inside params:{} once")
    a("// killed the editor). This table is what makes it possible to ANSWER \"nobody reads")
    a("// that key\" instead of swallowing it.")
    a("//")
    a("// It is NOT a validator: the dispatcher REPORTS the finding (data.unknown_params)")
    a("// and runs the command anyway. Rejecting would break existing callers.")
    a("//")
    a(f"// Coverage: {n_cmds} commands / {n_params} param names.")
    a("#pragma once")
    a("")
    a("#include \"CoreMinimal.h\"")
    a("")
    a("class FJsonObject;")
    a("")
    a("namespace McpCommandParamTable")
    a("{")
    a("    /** Number of commands in the table (= commands in command_catalog.json). */")
    a("    UEAGENT_API int32 NumCommands();")
    a("")
    a("    /**")
    a("     * Known param names of CommandName, or nullptr when the command is NOT in the")
    a("     * table. nullptr means \"unknown command, no opinion\" -- never \"no params\".")
    a("     * Keys are FName, so lookups are case-insensitive, matching FJsonObject's own")
    a("     * field lookup (its key map compares case-insensitively too).")
    a("     */")
    a("    UEAGENT_API const TSet<FName>* FindKnownParams(FName CommandName);")
    a("")
    a("    /**")
    a("     * True for envelope keys and dispatcher-wide params that are never a param of one")
    a("     * command (command_type, id, force, ...). The single list, with the evidence for")
    a("     * each entry, is in the .cpp.")
    a("     */")
    a("    UEAGENT_API bool IsProtocolKey(FName Key);")
    a("")
    a("    /**")
    a("     * Appends to OutUnknown, sorted, every top-level key of Params that is neither")
    a("     * a known param of CommandType nor a protocol key.")
    a("     *")
    a("     * Returns FALSE when CommandType is not in the table -- the caller must then")
    a("     * stay silent instead of inventing a verdict about a command it does not know")
    a("     * (a command the catalog does not publish). Returns true with an EMPTY")
    a("     * OutUnknown when everything is known.")
    a("     */")
    a("    UEAGENT_API bool CollectUnknownParams(")
    a("        const FString& CommandType,")
    a("        const TSharedPtr<FJsonObject>& Params,")
    a("        TArray<FString>& OutUnknown);")
    a("}")
    a("")
    return "\n".join(lines)


def render_flat_table(table: dict[str, list[str]]) -> list[str]:
    """One `TEXT("cmd"), TEXT("p1"), ..., nullptr,` group per command."""
    out: list[str] = []
    for cmd, params in table.items():
        out.append(f'    TEXT("{cmd}"),')
        line = "       "
        for p in params:
            piece = f' TEXT("{p}"),'
            if len(line) + len(piece) > WRAP_COLUMN:
                out.append(line)
                line = "       "
            line += piece
        if line.strip():
            out.append(line)
        out.append("    nullptr,")
    return out


def render_cpp(table: dict[str, list[str]]) -> str:
    n_cmds = len(table)
    n_params = sum(len(v) for v in table.values())
    lines: list[str] = []
    a = lines.append
    a(banner("Data + lookups of the known-param table."))
    a(f"#include \"{HEADER_NAME}\"")
    a("")
    a("#include \"Dom/JsonObject.h\"")
    a("#include \"Dom/JsonValue.h\"")
    a("")
    a("namespace McpCommandParamTable")
    a("{")
    a("// Named (NOT anonymous) namespace on purpose: this module builds with")
    a("// bUseUnity = true and anonymous-namespace helpers have collided across unity")
    a("// blobs in this plugin before (see bUseUnity in UEAgent.Build.cs).")
    a("namespace Generated")
    a("{")
    a("")
    a("// ---------------------------------------------------------------------------")
    a("// Protocol keys: they ride in the request but are NOT params of any command.")
    a("// ONE list, here, with the evidence for each entry. A key that IS a real param")
    a("// of the command (`type` for spawn_actor, `command` for execute_console_command,")
    a("// `force` for start_play_in_editor) is matched against the command's known set")
    a("// FIRST, so listing it here never hides it.")
    a("// ---------------------------------------------------------------------------")
    a("static const TCHAR* const GProtocolKeys[] =")
    a("{")
    for key, why in PROTOCOL_KEYS:
        # Wrap the rationale so the generated file stays readable.
        words = why.split()
        chunks: list[str] = []
        cur = ""
        for w in words:
            if cur and len(cur) + 1 + len(w) > 74:
                chunks.append(cur)
                cur = w
            else:
                cur = f"{cur} {w}".strip()
        if cur:
            chunks.append(cur)
        a(f"    // {chunks[0]}")
        for extra in chunks[1:]:
            a(f"    //   {extra}")
        a(f'    TEXT("{key}"),')
    a("};")
    a("")
    a("// ---------------------------------------------------------------------------")
    a("// The table itself, FLAT: for each command, its name followed by its known param")
    a("// names and a nullptr terminator; one extra nullptr closes the array. Walked")
    a("// exactly ONCE (see GetTable) into a static map -- nothing is rebuilt per call,")
    a("// and one array of literals is far cheaper object code than one Add() per")
    a(f"// command ({n_cmds} of them).")
    a("//")
    a("// A command with an EMPTY param set is still in the table (name + terminator):")
    a("// \"this command takes no params\" is a real answer, and different from \"I do not")
    a("// know this command\", which is the absence of the entry.")
    a("// ---------------------------------------------------------------------------")
    a("static const TCHAR* const GFlatCommandParams[] =")
    a("{")
    lines.extend(render_flat_table(table))
    a("    // End of table: this extra nullptr is what stops the outer walk.")
    a("    nullptr")
    a("};")
    a("")
    a(f"static constexpr int32 GNumCommands = {n_cmds};")
    a(f"static constexpr int32 GNumParamNames = {n_params};")
    a("")
    a("// Built ONCE, on first use (function-local static => thread-safe init). The")
    a("// dispatcher is game-thread only, so there is no contention after that.")
    a("static const TMap<FName, TSet<FName>>& GetTable()")
    a("{")
    a("    static const TMap<FName, TSet<FName>> Table = []()")
    a("    {")
    a("        TMap<FName, TSet<FName>> Out;")
    a("        Out.Reserve(GNumCommands);")
    a("        int32 Index = 0;")
    a("        while (GFlatCommandParams[Index] != nullptr)")
    a("        {")
    a("            TSet<FName>& Known = Out.Add(FName(GFlatCommandParams[Index++]));")
    a("            while (GFlatCommandParams[Index] != nullptr)")
    a("            {")
    a("                Known.Add(FName(GFlatCommandParams[Index++]));")
    a("            }")
    a("            ++Index; // step over this command's terminator")
    a("        }")
    a("        return Out;")
    a("    }();")
    a("    return Table;")
    a("}")
    a("")
    a("static const TSet<FName>& GetProtocolKeys()")
    a("{")
    a("    static const TSet<FName> Keys = []()")
    a("    {")
    a("        TSet<FName> Out;")
    a("        for (const TCHAR* const Key : GProtocolKeys)")
    a("        {")
    a("            Out.Add(FName(Key));")
    a("        }")
    a("        return Out;")
    a("    }();")
    a("    return Keys;")
    a("}")
    a("")
    a("} // namespace Generated")
    a("")
    a("int32 NumCommands()")
    a("{")
    a("    return Generated::GetTable().Num();")
    a("}")
    a("")
    a("const TSet<FName>* FindKnownParams(FName CommandName)")
    a("{")
    a("    return Generated::GetTable().Find(CommandName);")
    a("}")
    a("")
    a("bool IsProtocolKey(FName Key)")
    a("{")
    a("    return Generated::GetProtocolKeys().Contains(Key);")
    a("}")
    a("")
    a("bool CollectUnknownParams(")
    a("    const FString& CommandType,")
    a("    const TSharedPtr<FJsonObject>& Params,")
    a("    TArray<FString>& OutUnknown)")
    a("{")
    a("    const TSet<FName>* Known = FindKnownParams(FName(*CommandType));")
    a("    if (Known == nullptr)")
    a("    {")
    a("        // Not in the table => no verdict. Saying \"unknown param\" about a command")
    a("        // whose param set we do not have would be exactly the kind of fabricated")
    a("        // claim this whole feature exists to kill.")
    a("        return false;")
    a("    }")
    a("    if (!Params.IsValid())")
    a("    {")
    a("        return true;")
    a("    }")
    a("")
    a("    TArray<FString> Found;")
    a("    for (const auto& Pair : Params->Values)")
    a("    {")
    a("        // `*Pair.Key` is a const TCHAR* for BOTH key storages FJsonObject can be")
    a("        // built with in UE 5.8 (FString and UE::FSharedString both expose")
    a("        // operator*), so this compiles whatever UE_JSONOBJECT_LEGACY_STRING_KEYS is.")
    a("        const TCHAR* KeyChars = *Pair.Key;")
    a("        const int32 KeyLen = Pair.Key.Len();")
    a("")
    a("        // A key at/over NAME_SIZE cannot be an FName (FName::Init checkf's on it,")
    a("        // i.e. constructing one would CRASH the editor) and cannot be a catalog")
    a("        // param either, so it is reported directly -- truncated, so a garbage frame")
    a("        // cannot blow up the response it is being reported in.")
    a("        if (KeyLen >= NAME_SIZE)")
    a("        {")
    a("            Found.Add(FString::ConstructFromPtrSize(KeyChars, 128) + TEXT(\"...(truncated)\"));")
    a("            continue;")
    a("        }")
    a("")
    a("        const FName Key(KeyChars);")
    a("        if (Known->Contains(Key) || IsProtocolKey(Key))")
    a("        {")
    a("            continue;")
    a("        }")
    a("        Found.Add(FString(KeyChars));")
    a("    }")
    a("")
    a("    // Deterministic order: the same malformed call must always report the same")
    a("    // array (FJsonObject's key map has no defined iteration order).")
    a("    Found.Sort();")
    a("    OutUnknown.Append(MoveTemp(Found));")
    a("    return true;")
    a("}")
    a("")
    a("} // namespace McpCommandParamTable")
    a("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def read_if_exists(path: str) -> str | None:
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8", newline="") as f:
        return f.read()


def write_text(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    # newline="\n": the generated C++ must not flip line endings between machines,
    # or every run of the codegen shows up as a whole-file diff.
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write(text)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--write", action="store_true",
                   help=f"regenerate {HEADER_NAME} / {SOURCE_NAME}")
    p.add_argument("--check", action="store_true",
                   help="exit non-zero if the on-disk generated files differ from "
                        "what the catalog says they should be")
    a = p.parse_args()

    if not os.path.exists(CATALOG_JSON):
        print(f"ERROR: catalog not found: {CATALOG_JSON}")
        return 3
    table = load_catalog(CATALOG_JSON)
    problems = validate(table)
    if problems:
        print(f"ERROR: {len(problems)} unusable name(s) in the catalog; refusing to emit C++")
        for w in problems[:20]:
            print(f"  {w}")
        return 4

    header = render_header(table)
    cpp = render_cpp(table)

    n_cmds = len(table)
    n_params = sum(len(v) for v in table.values())
    n_empty = sum(1 for v in table.values() if not v)
    widest = max(table.items(), key=lambda kv: len(kv[1]))

    print("=" * 78)
    print(f"CATALOG : {CATALOG_JSON}")
    print(f"COMMANDS: {n_cmds}  ({n_empty} with no params)")
    print(f"PARAMS  : {n_params} names  (widest: {widest[0]} = {len(widest[1])})")
    print(f"PROTOCOL: {len(PROTOCOL_KEYS)} excluded keys "
          f"({', '.join(k for k, _ in PROTOCOL_KEYS)})")
    print(f"HEADER  : {OUT_H}  ({header.count(chr(10))} lines)")
    print(f"SOURCE  : {OUT_CPP}  ({cpp.count(chr(10))} lines)")
    print("=" * 78)

    if a.check:
        drift = False
        for path, want in ((OUT_H, header), (OUT_CPP, cpp)):
            have = read_if_exists(path)
            if have is None:
                print(f"MISSING : {path} — re-run with --write")
                drift = True
            elif have != want:
                print(f"DRIFT   : {path} differs from the catalog — re-run with --write")
                drift = True
        if drift:
            return 1
        print("  generated table in sync with the catalog")
        return 0

    if a.write:
        write_text(OUT_H, header)
        write_text(OUT_CPP, cpp)
        print(f"WROTE   : {OUT_H}")
        print(f"WROTE   : {OUT_CPP}")
    else:
        print()
        print("(dry-run; pass --write to apply)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
