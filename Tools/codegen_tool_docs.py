"""
codegen_tool_docs.py -- the tool reference (docs/tools/), generated from Resources/command_catalog.json.

One Markdown page per domain, every tool with its description, parameters and return shape, plus an index
(docs/tools/README.md). The catalog is generated from the C++ annotations, so the reference follows the code:
run it after codegen_command_catalog.py.

Usage:
  python Tools/codegen_tool_docs.py            # report what would change
  python Tools/codegen_tool_docs.py --write    # regenerate docs/tools/
  python Tools/codegen_tool_docs.py --check    # fail if docs/tools/ drifted from the catalog
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _paths  # noqa: E402

OUT_DIR = os.path.join(_paths.PLUGIN_ROOT, "docs", "tools")
HEADER = "<!-- Generated by Tools/codegen_tool_docs.py from Resources/command_catalog.json: do not edit. -->"

def prose(text: str) -> str:
    """Text with `<` escaped outside code spans, so GitHub does not take `<x>` for an HTML tag."""
    out, at = [], 0
    for m in re.finditer(r'(`+)(.+?)\1', text, re.S):
        out += [text[at:m.start()].replace("<", "&lt;"), m.group(0)]
        at = m.end()
    out.append(text[at:].replace("<", "&lt;"))
    return "".join(out)


def code(text: str) -> str:
    """An inline code span for text that may itself hold backticks."""
    text = " ".join(text.split())
    longest = max((len(run) for run in re.findall(r'`+', text)), default=0)
    fence = "`" * (longest + 1)
    pad = " " if longest else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def cell(text: str) -> str:
    """Text for one Markdown table cell."""
    return prose(" ".join(str(text).split())).replace("|", "\\|") or " "


def hints(annotations: dict | None) -> str:
    """The tool's MCP annotations, in words: what a call does to the project."""
    if not annotations:
        return ""
    if annotations.get("readOnlyHint"):
        words = ["read-only"]
    else:
        words = ["destructive" if annotations.get("destructiveHint", True) else "additive"]
        if annotations.get("idempotentHint"):
            words.append("idempotent")
    if annotations.get("openWorldHint"):
        words.append("open world")
    return "*" + ", ".join(words).capitalize() + ".*"


def summary(domain: dict) -> str:
    """What the domain covers: its catalog `description` (DOMAINS in codegen_command_catalog.py), or the first tool
    names when it has none. The intro of its page, the index's last column and the page's description on the site."""
    if domain.get("description"):
        return domain["description"]
    names = sorted(c["name"] for c in domain["commands"])
    return ", ".join(f"`{n}`" for n in names[:4]) + (", ..." if len(names) > 4 else "")


def domain_page(entry: dict) -> str:
    domain, commands = entry["domain"], entry["commands"]
    count = f"{len(commands)} tool" + ("" if len(commands) == 1 else "s")
    lines = [HEADER, "", f"# {domain}", "",
             f"{count} for {summary(entry)}.", "",
             "Back to the [index](README.md).", ""]
    for c in sorted(commands, key=lambda c: c["name"]):
        lines += [f"## `{c['name']}`", ""]
        if hints(c.get("annotations")):
            lines += [hints(c.get("annotations")), ""]
        if c.get("core"):
            lines += ["**Core tool:** every client lists it by default.", ""]
        elif c.get("pack"):
            lines += [f"**Pack `{c['pack']}`:** `enable_toolset` adds it to a client's list "
                      "([tool lists](../clients.md#tool-lists)).", ""]
        lines += [prose(c.get("description") or "No description."), ""]
        params = c.get("params") or []
        if params:
            lines += ["| Parameter | Type | Required | Description |", "|---|---|---|---|"]
            for p in params:
                lines.append(f"| `{p['name']}` | {cell(p.get('jsonType') or 'any')} | "
                             f"{'yes' if p.get('required') else 'no'} | {cell(p.get('description') or '')} |")
            lines.append("")
        else:
            lines += ["No parameters.", ""]
        if c.get("returns"):
            lines += [f"**Returns:** {code(c['returns'])}", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def index_page(domains: list[dict], has_retired: bool = False, packs: list[dict] | None = None) -> str:
    total = sum(len(d["commands"]) for d in domains)
    core = sorted(c["name"] for d in domains for c in d["commands"] if c.get("core"))
    lines = [HEADER, "", "# Tool reference", "",
             f"{total} tools in {len(domains)} domains. Every tool also describes itself over MCP "
             "(`tools/list`, or `describe_tool` for a tool the client does not list: see "
             "[tool lists](../clients.md#tool-lists)); this reference is the same catalog, readable.", "",
             f"The {len(core)} core tools, which every client lists by default: "
             + ", ".join(f"`{name}`" for name in core) + ".", ""]
    if packs:
        lines += ["The packs, which `enable_toolset` adds by name:", "", "| Pack | Tools | For |", "|---|---|---|"]
        for pack in packs:
            tools = sorted(c["name"] for d in domains for c in d["commands"] if c.get("pack") == pack["name"])
            lines.append(f"| `{pack['name']}` | {', '.join(f'`{name}`' for name in tools)} | "
                         f"{cell(pack['description'][:1].upper() + pack['description'][1:])} |")
        lines.append("")
    lines += ["| Domain | Tools | What it covers |", "|---|---|---|"]
    for d in domains:
        covers = summary(d)
        lines.append(f"| [{d['domain']}]({d['domain']}.md) | {len(d['commands'])} | "
                     f"{cell(covers[:1].upper() + covers[1:])} |")
    if has_retired:
        lines += ["", "Old and retired names that still run are in [Retired names](retired.md)."]
    return "\n".join(lines) + "\n"


def retired_page(renamed: dict[str, str], retired: list[dict]) -> str:
    """The names that still run but are not listed: renamed tools' old names, and retired tools."""
    lines = [HEADER, "", "# Retired names", "",
             "These names are not in the tool list, and a call to them still works until UEAgent 3.0: the reply's "
             "`data.retired_name` says what to call instead.", "",
             "Back to the [index](README.md).", ""]
    if renamed:
        lines += ["## Renamed", "", "The old name runs the new tool: same parameters, same reply.", "",
                  "| Old name | New name |", "|---|---|"]
        retired_use = {c["name"]: c["retired"]["use"] for c in retired}
        lines += [f"| `{old}` | `{new}`" + (f" (retired: `{retired_use[new]}` does the same)" if new in retired_use else "") + " |"
                  for old, new in sorted(renamed.items())]
        lines.append("")
    if retired:
        lines += ["## Retired", "", "The tool still runs under its own name; the listed tool does the same.", "",
                  "| Retired | Use | How |", "|---|---|---|"]
        lines += [f"| `{c['name']}` | `{c['retired']['use']}` | {cell(c['retired'].get('how') or '')} |"
                  for c in sorted(retired, key=lambda c: c["name"])]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render() -> dict[str, str]:
    with open(_paths.CATALOG_JSON, encoding="utf-8") as f:
        catalog = json.load(f)
    retired = [c for d in catalog["domains"] for c in d["commands"] if c.get("retired")]
    renamed = catalog.get("renamed") or {}
    domains = []
    for d in sorted(catalog["domains"], key=lambda d: d["domain"]):
        listed = [c for c in d["commands"] if not c.get("retired")]
        if listed:
            domains.append({"domain": d["domain"], "description": d.get("description", ""), "commands": listed})
    pages = {"README.md": index_page(domains, bool(retired or renamed), catalog.get("packs") or [])}
    for d in domains:
        pages[f"{d['domain']}.md"] = domain_page(d)
    if retired or renamed:
        pages["retired.md"] = retired_page(renamed, retired)
    return pages


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--write", action="store_true", help="regenerate docs/tools/")
    p.add_argument("--check", action="store_true", help="fail if docs/tools/ drifted from the catalog")
    args = p.parse_args()

    pages = render()
    on_disk = set(os.listdir(OUT_DIR)) if os.path.isdir(OUT_DIR) else set()
    stale = sorted(on_disk - set(pages))
    changed = []
    for name, text in pages.items():
        path = os.path.join(OUT_DIR, name)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None  # any line ending
        if old != text:
            changed.append(name)
    print(f"{len(pages)} pages, {len(changed)} changed, {len(stale)} stale")

    if args.check:
        if changed or stale:
            print("DOCS DRIFT: run Tools/codegen_tool_docs.py --write")
            for name in changed + stale:
                print(f"  {name}")
            return 1
        print("  tool reference in sync with the catalog")
        return 0
    if args.write:
        os.makedirs(OUT_DIR, exist_ok=True)
        for name in changed:
            with open(os.path.join(OUT_DIR, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(pages[name])
        for name in stale:
            os.remove(os.path.join(OUT_DIR, name))
        print(f"WROTE   : {OUT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
